
from unittest.mock import patch

from langchain_core.messages import AIMessage

from core.llm import (
    llm,
    clear_used_providers,
    get_last_used_provider,
    get_used_providers,
    extract_response_text
)


# ==================================================
# TEST 1: NORMAL HYBRID MODEL EXECUTION
# ==================================================

def test_hybrid_model_execution():

    clear_used_providers()

    print("\nTesting Hybrid LLM...")
    print("Trying Gemini first, then Ollama if needed.")

    response = llm.invoke(
        "Explain what a research paper is in two sentences."
    )

    result = extract_response_text(response)

    provider = get_last_used_provider()
    providers = get_used_providers()

    print("\nProvider Used:", provider)
    print("Providers Used:", providers)
    print("\nResponse:")
    print(result)

    assert isinstance(result, str)
    assert len(result.strip()) > 0

    assert provider in ["Gemini", "Ollama"]
    assert provider in providers


# ==================================================
# TEST 2: GEMINI FAILURE AND OLLAMA FALLBACK
# ==================================================

def test_hybrid_fallback_to_ollama():

    clear_used_providers()

    print("\nTesting Gemini failure and Ollama fallback...")

    # Simulate a Gemini quota error.
    class GeminiQuotaError(Exception):
        status_code = 429

    # Replace the model objects with mocks.
    with patch("core.llm.gemini_llm") as mock_gemini, \
         patch("core.llm.ollama_llm") as mock_ollama:

        # Make Gemini fail.
        mock_gemini.invoke.side_effect = GeminiQuotaError(
            "Gemini quota exceeded"
        )

        # Simulate a successful Ollama response.
        mock_ollama.invoke.return_value = AIMessage(
            content="This response was generated by Ollama."
        )

        # Execute the hybrid model.
        response = llm.invoke(
            "Explain artificial intelligence."
        )

        result = extract_response_text(response)

        print("\nProvider Used:", get_last_used_provider())
        print("Providers Used:", get_used_providers())
        print("\nResponse:", result)

        # Verify Gemini was attempted.
        mock_gemini.invoke.assert_called_once()

        # Verify Ollama was called after Gemini failed.
        mock_ollama.invoke.assert_called_once()

        # Verify the fallback response.
        assert result == "This response was generated by Ollama."

        # Verify provider tracking.
        assert get_last_used_provider() == "Ollama"

        assert get_used_providers() == ["Ollama"]
